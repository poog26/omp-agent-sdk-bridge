// OMP's personality as Claude Code's output style.
//
// Claude Code's preset carries a tone section written for a terminal ("be concise",
// CLI formatting). Output styles are Claude Code's own mechanism for replacing that
// section, and `keep-coding-instructions: true` keeps everything else. The bridge
// writes OMP's personality block (PERSONALITY.md or the configured preset) into a
// tiny local plugin it owns and selects it per query, so OMP stays the single source
// of the persona and nothing is written into the user's ~/.claude.
//
// Measured with Agent SDK 0.3.308: a plugin output style applies only when selected
// as "<plugin name>:<style name>"; the bare style name is silently ignored.
//
// Each distinct persona gets its own content-addressed file, so sessions with
// different personas never overwrite each other's style mid-flight.

import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export const PERSONA_PLUGIN_NAME = "omp-bridge";
const STYLE_PREFIX = "omp-persona-";
const KEEP_RECENT_STYLES = 8;

export interface PersonaStyle {
	pluginPath: string;
	/** Value for settings.outputStyle. */
	outputStyle: string;
}

/** The persona text without OMP's "# Personality" heading. */
export function personaBody(personalitySection: string): string {
	return personalitySection.replace(/^#\s*Personality\s*\n/, "").trim();
}

export function styleFileContent(name: string, body: string): string {
	return [
		"---",
		`name: ${name}`,
		"description: Persona from Oh My Pi (PERSONALITY.md), supplied by omp-agent-sdk-bridge",
		"keep-coding-instructions: true",
		"---",
		"",
		body,
		"",
	].join("\n");
}

/**
 * Ensure the plugin holds a style for this persona and return how to select it.
 * Writes only when the persona is new; prunes old styles beyond a small cache.
 */
export function ensurePersonaStyle(personalitySection: string, pluginRoot: string): PersonaStyle | undefined {
	const body = personaBody(personalitySection);
	if (!body) return undefined;
	const hash = createHash("sha256").update(body).digest("hex").slice(0, 10);
	const styleName = `OMP Persona ${hash}`;

	const manifestDir = join(pluginRoot, ".claude-plugin");
	const stylesDir = join(pluginRoot, "output-styles");
	const manifestPath = join(manifestDir, "plugin.json");
	const stylePath = join(stylesDir, `${STYLE_PREFIX}${hash}.md`);

	mkdirSync(manifestDir, { recursive: true });
	mkdirSync(stylesDir, { recursive: true });
	const manifest = JSON.stringify({
		name: PERSONA_PLUGIN_NAME,
		version: "1.0.0",
		description: "Output styles generated by omp-agent-sdk-bridge from OMP's personality",
	}, null, 2) + "\n";
	if (!existsSync(manifestPath) || readFileSync(manifestPath, "utf-8") !== manifest) writeFileSync(manifestPath, manifest);

	const content = styleFileContent(styleName, body);
	if (!existsSync(stylePath) || readFileSync(stylePath, "utf-8") !== content) writeFileSync(stylePath, content);
	pruneOldStyles(stylesDir, `${STYLE_PREFIX}${hash}.md`);

	return { pluginPath: pluginRoot, outputStyle: `${PERSONA_PLUGIN_NAME}:${styleName}` };
}

function pruneOldStyles(stylesDir: string, keep: string): void {
	try {
		const files = readdirSync(stylesDir)
			.filter((f) => f.startsWith(STYLE_PREFIX) && f.endsWith(".md") && f !== keep)
			.map((f) => ({ f, mtime: statSync(join(stylesDir, f)).mtimeMs }))
			.sort((a, b) => a.mtime - b.mtime);
		if (files.length < KEEP_RECENT_STYLES) return;
		// Drop the least recently written styles; the cache only bounds disk use.
		for (const { f } of files.slice(0, files.length - KEEP_RECENT_STYLES + 1)) rmSync(join(stylesDir, f), { force: true });
	} catch { /* best effort */ }
}
